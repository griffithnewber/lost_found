-- §与旧环境的差异（都核过，不影响任何功能）
--   1. RLS：旧环境 lost_items / item_messages / users 开了 RLS，但 8 条策略全是
--      using(true) / with_check(true)，等于没有额外限制；新环境直接不开 RLS，
--      真正的边界仍然是上面的**列权限**（这才是拦 detail 的那一层，已实测 401）。
--      实测矩阵（anon，select/insert/update/delete）两环境一致：
--        lost_items    列级 SELECT / T / T / T
--        item_messages T / T / F / F
--        locations     T / F / F / F
--        users         T / T / F / F
--   2. authenticated 在 lost_items 上旧环境多 TRUNCATE/REFERENCES/TRIGGER/MAINTAIN
--      （默认权限带出来的），PostgREST 用不到这四项，新环境未授予。
--   3. locations.id：旧 serial，新 identity；都是自增主键，写入方只走服务端。
--   差异曾经存在的「坑」（已修，留作教训）：
--      · 建库时为了灌数据临时给 anon 开过 locations INSERT、users UPDATE、
--        item_messages UPDATE/DELETE —— 已 REVOKE，anon 现在与旧环境逐项相同；
--      · 漏建 idx_users_username 时**同名用户能重复注册**（因唯一性是靠索引实现的，
--        不是 CONSTRAINT），现已补上，重复注册返回 409。
