-- §1 表结构（与旧环境逐列一致，identity 主键）
CREATE TABLE IF NOT EXISTS public.lost_items (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title text NOT NULL, detail text, location text, image text, color_feature jsonb, pub_time text, created_at timestamptz NOT NULL DEFAULT now(), ai_desc text, ai_tags jsonb, status text NOT NULL DEFAULT 'open', owner_id text, claim_at timestamptz, post_type text NOT NULL DEFAULT 'lost', notice text, category text, color_tone text, pickup_location text, area text);
CREATE TABLE IF NOT EXISTS public.item_messages (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id bigint NOT NULL, role text NOT NULL DEFAULT 'finder', name text, contact text, content text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), sender_id text);
CREATE TABLE IF NOT EXISTS public.locations (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, address text, open_hours text, note text, zone text);
CREATE TABLE IF NOT EXISTS public.users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username text NOT NULL, pass_salt text NOT NULL, pass_hash text NOT NULL, created_at timestamptz NOT NULL DEFAULT now());


-- §2 索引（与旧环境同名同定义；idx_users_username 是大小写不敏感唯一，
--     assets/auth.js 登录用 ilike 查用户名，靠它保证「Alice / alice」不会重复注册）
CREATE INDEX IF NOT EXISTS idx_lost_items_created_id_desc ON public.lost_items USING btree (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_item_messages_item ON public.item_messages USING btree (item_id, created_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username ON public.users USING btree (lower(username));


-- §3 lost_items 权限：公开密钥**只能读 15 个公开列**，
--    detail / location / ai_desc / ai_tags 永不授权（防 AI 描述泄露独特征 → 冒领）
REVOKE ALL ON TABLE public.lost_items FROM anon, authenticated;
GRANT SELECT (id, title, image, color_feature, notice, category, color_tone, status, post_type, owner_id, pickup_location, claim_at, pub_time, created_at, area) ON TABLE public.lost_items TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON TABLE public.lost_items TO anon, authenticated;

-- §4 留言：匿名可读可写，**不可改不可删**（删改只走服务端/阿寻）
REVOKE UPDATE, DELETE ON TABLE public.item_messages FROM anon;
GRANT SELECT, INSERT ON TABLE public.item_messages TO anon, authenticated;
GRANT UPDATE, DELETE ON TABLE public.item_messages TO authenticated, service_role;

-- §5 寄存点：只读（新增寄存点走服务端）
REVOKE INSERT, UPDATE, DELETE ON TABLE public.locations FROM anon;
GRANT SELECT ON TABLE public.locations TO anon, authenticated;

-- §6 站点账号：匿名只能查 + 注册，**不能改**（改了就能覆盖别人的 pass_hash）
REVOKE UPDATE ON TABLE public.users FROM anon;
GRANT SELECT, INSERT ON TABLE public.users TO anon, authenticated;
GRANT UPDATE ON TABLE public.users TO authenticated, service_role;

-- §7 身份列序列：授权不足时 INSERT 会报 permission denied for sequence
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;


